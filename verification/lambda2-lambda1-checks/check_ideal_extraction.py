"""Every f,h plane in each V(Q), including affine planes, modulo constants.
I is the Boolean ideal generated by the FUNCTION a0*b0. If fh mod I is
quadratic, its quadratic part must have a rank <=2 representative modulo Q.
All quadratic R congruent to fh differ only by P0, so both are tested.
"""
from core import *
from collections import Counter
I_MASK=sum(1<<m for m in range(64) if m&9==9)
KEEP=FULL^I_MASK

def increment(Q,R):
    return any(R^q==0 or R^q in R2_SET for q in elements(Q))

def main():
    start=time.time();c=Counter();wc=Counter()
    # Check the support-based construction, using actual products rather than
    # pure quadratic representatives. This catches Boolean diagonal terms.
    for P in R2:
        if P==P0:continue
        l,r=R2_FACTORS[P];p=mul(linear(l),linear(r));Q=basis((P0,P))
        for b in range(1,64):
            B=linear(b);pb=mul(p,B);cub=pb&DEG[3]
            if cub&KEEP:continue
            c['construction_cases']+=1
            if not cub:
                assert pb in (0,p)
                continue
            W=basis((l,r,b));assert len(W)==3
            Wvals=elements(W)
            L=next(d for d in Wvals if mul(P0,linear(d))&DEG[3]==cub)
            C=pb^mul(P0,linear(L));assert degree(C)<=2
            assert any(reduce((C&DEG[2])^wedge(b,d),Q)==0 for d in Wvals)
    for Q,w in q2_orbits():
        vals=elements(X+Q);tt=[mob(v) for v in vals]
        for i,j in planes(len(X+Q),None):
            p=mob(tt[i]&tt[j]);r=p&KEEP
            c['planes']+=1;wc['planes']+=w
            if r&HIGH2:continue
            c['quadratic_quotient_planes']+=1;wc['quadratic_quotient_planes']+=w
            assert increment(Q,r&DEG[2]),(Q,vals[i],vals[j],p,r)
            assert increment(Q,(r^P0)&DEG[2])
            c['quadratic_representatives']+=2
            for f,h in [(vals[i]^1,vals[j]),(vals[i],vals[j]^1),(vals[i],vals[i]^vals[j])]:
                rr=mul(f,h)&KEEP
                assert not rr&HIGH2 and increment(Q,rr&DEG[2])
        # All descriptions dependent modulo constants yield an available signal.
        for f in elements(AFF+Q):
            for p in (mul(f,f),mul(f,f^1),mul(f,1),mul(f,0)):
                r=p&KEEP
                assert not r&HIGH2 and increment(Q,r&DEG[2])
                c['dependent_descriptions']+=1
    # Dropping the product hypothesis admits a known forbidden quadratic.
    Q=(P0,);relaxed=Z1&KEEP
    assert not relaxed&HIGH2 and not increment(Q,relaxed&DEG[2])
    record('ideal_extraction',{'status':'PASS','Q_orbits':83,'Q_spaces':606,
      'counts':dict(c),'weighted_counts':dict(wc),'positive_controls_detected':1,
      'domain':'all f,h in every normalized rank-two-generated Q of dimension <=2, via planes, constants and dependent factors; all quadratic R congruent modulo I',
      'seconds':round(time.time()-start,3)})
if __name__=='__main__':main()
